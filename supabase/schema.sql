-- Clientes con datos de persona aplanados
create or replace view public.vw_clientes as
select
  c.id                as id,
  c.id               as "clienteId",
  c.id_persona        as "idPersona",
  c.tipo              as tipo,
  c.estado            as estado,
  c.fecha_creacion    as "fechaCreacion",
  c.fecha_actualizacion as "fechaActualizacion",
  p.tipo_documento    as "tipoDocumento",
  p.numero_documento  as "numeroDocumento",
  p.nombres           as nombres,
  p.apellido_paterno  as "apellidoPaterno",
  p.apellido_materno  as "apellidoMaterno",
  p.correo            as correo,
  p.telefono          as telefono,
  p.fecha_nacimiento  as "fechaNacimiento",
  p.direccion         as direccion
from public.cliente c
join public.persona p on p.id = c.id_persona;

-- Empleados con persona + departamento
create or replace view public.vw_empleados as
select
  e.id, e.id_persona as "idPersona", e.departamento_id as "departamentoId",
  e.puesto, e.sueldo, e.fecha_contratacion as "fechaContratacion",
  e.foto, e.cv, e.estado,
  e.fecha_creacion as "fechaCreacion", e.fecha_actualizacion as "fechaActualizacion",
  p.tipo_documento as "tipoDocumento", p.numero_documento as "numeroDocumento",
  p.nombres, p.apellido_paterno as "apellidoPaterno", p.apellido_materno as "apellidoMaterno",
  p.correo, p.telefono, p.fecha_nacimiento as "fechaNacimiento", p.direccion,
  d.nombre as "departamentoNombre"
from public.empleado e
join public.persona p on p.id = e.id_persona
left join public.departamento d on d.id = e.departamento_id;

-- Productos con categoría y stock total
create or replace view public.vw_productos as
select
  pr.*,
  cp.nombre as "categoriaNombre",
  coalesce((select sum(i.stock_actual) from public.inventario i where i.id_producto = pr.id), 0) as "stockTotal"
from public.producto pr
left join public.categoria_producto cp on cp.id = pr.categoria_id;

-- Usuarios con persona y rol (para el módulo de Accesos)
create or replace view public.vw_usuarios as
select
  u.id, u.id_persona as "idPersona", u.id_rol as "idRol",
  u.username, u.estado, u.auth_user_id as "authUserId",
  u.fecha_creacion as "fechaCreacion",
  p.nombres, p.apellido_paterno as "apellidoPaterno", p.apellido_materno as "apellidoMaterno",
  p.correo, p.telefono, p.numero_documento as "numeroDocumento",
  r.nombre as "rolNombre"
from public.usuario u
join public.persona p on p.id = u.id_persona
join public.rol r on r.id = u.id_rol;

