-- ============================================================================
-- Peru Market ERP — Esquema completo para Supabase (PostgreSQL)
-- ----------------------------------------------------------------------------
-- Conversión de `perumarket_erp - origin.sql` (MariaDB) a PostgreSQL.
--
-- CÓMO USARLO:
--   1. Supabase → SQL Editor → New query
--   2. Pega TODO este archivo y ejecuta (RUN).
--   3. Luego ejecuta `seed.sql` para cargar los datos.
--   4. Crea tu usuario admin (ver el final de este archivo / README).
--
-- Notas de conversión:
--   * enum(...)            -> text + CHECK
--   * tinyint(1)           -> boolean
--   * int AUTO_INCREMENT   -> bigint generated by default as identity
--   * decimal(p,s)         -> numeric(p,s)
--   * timestamp ON UPDATE  -> timestamptz + trigger set_updated_at()
--   * Se mantienen los MISMOS nombres de tablas/columnas que el original.
-- ============================================================================

-- Limpieza idempotente (puedes re-ejecutar este script sin problemas)
drop schema if exists public cascade;
create schema public;
grant usage on schema public to anon, authenticated, service_role;
alter default privileges in schema public grant all on tables to anon, authenticated, service_role;
alter default privileges in schema public grant all on sequences to anon, authenticated, service_role;

-- ----------------------------------------------------------------------------
-- Trigger genérico para `fecha_actualizacion`
-- ----------------------------------------------------------------------------
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.fecha_actualizacion := now();
  return new;
end;
$$;

