-- ============================================================================
-- TRIGGERS updated_at (fecha_actualizacion) en todas las tablas
-- ============================================================================
do $$
declare t text;
begin
  for t in
    select table_name from information_schema.columns
    where table_schema = 'public' and column_name = 'fecha_actualizacion'
  loop
    execute format(
      'create trigger trg_%1$s_updated before update on public.%1$s
       for each row execute function public.set_updated_at();', t);
  end loop;
end $$;

-- ============================================================================
-- ROW LEVEL SECURITY
-- ----------------------------------------------------------------------------
-- Se habilita RLS en todas las tablas y se permite acceso completo a usuarios
-- AUTENTICADOS (rol `authenticated`). Puedes endurecer estas políticas más
-- adelante por rol/usuario.
-- ============================================================================
do $$
declare t text;
begin
  for t in
    select tablename from pg_tables where schemaname = 'public'
  loop
    execute format('alter table public.%I enable row level security;', t);
    execute format(
      'create policy "authenticated_all_%1$s" on public.%1$s
       for all to authenticated using (true) with check (true);', t);
  end loop;
end $$;

-- ============================================================================
-- PUENTE CON SUPABASE AUTH
-- ----------------------------------------------------------------------------
-- Vincula automáticamente un usuario de Supabase Auth con su fila en
-- `public.usuario` haciendo match por email (persona.correo) o username.
-- Si no encuentra match, NO crea fila (debes crearla manualmente).
-- ============================================================================
create or replace function public.link_auth_user()
returns trigger language plpgsql security definer as $$
begin
  update public.usuario u
     set auth_user_id = new.id
   from public.persona p
  where u.id_persona = p.id
    and u.auth_user_id is null
    and (
      lower(p.correo) = lower(new.email)
      or lower(u.username) = lower(split_part(new.email, '@', 1))
    );
  return new;
end;
$$;

